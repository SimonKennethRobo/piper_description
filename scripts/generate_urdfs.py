#!/usr/bin/env python3
"""Generate the description's full URDFs from the SDK's plain URDFs plus the visuals overlay.

    generate_urdfs.py [--sdk-urdf-dir DIR] [--out DIR] [--check]

The SDK's plain URDFs (<model>[_gripper].urdf: kinematics and inertials, no meshes; model is
piper, piper_h, piper_l or piper_x) are THE source of the arm model. This package only adds
what a simulator, RViz or a digital twin needs: meshes, materials and collision geometry,
taken from overlay/ (materials.json, <model>.json, agx_gripper.json). Output, under --out
(default: urdf/generated of this package):

    ros/<name>.urdf   meshes as package://piper_description/meshes/...  (xacro entry
                      point urdf/piper_description.urdf.xacro includes these)
    sim/<name>.urdf   meshes relative to the file (../../../meshes/...): for simulators that
                      read a plain file (MuJoCo, ...), no ROS needed; movable gripper joints

SDK URDF directory: --sdk-urdf-dir, else $PIPER_SDK_URDF_DIR, else piper_sdk/urdf of the SDK
checkout this package is a submodule of (../piper_sdk/urdf) or sits next to
(../piper_control/piper_sdk/urdf).

--check generates into a temporary directory and compares with --out; exit 0 = up to date,
1 = out of date, 77 = no SDK URDF directory found (skipped; the CTest convention).
Python 3 standard library only.
"""
import argparse
import filecmp
import json
import os
import pathlib
import sys
import tempfile
import xml.etree.ElementTree as ET

PKG = "piper_description"
HERE = pathlib.Path(__file__).resolve().parent.parent
MODELS = ["piper", "piper_h", "piper_l", "piper_x"]


def find_sdk_urdf_dir(arg):
    candidates = [arg] if arg else []
    if not arg:
        if os.environ.get("PIPER_SDK_URDF_DIR"):
            candidates.append(os.environ["PIPER_SDK_URDF_DIR"])
        candidates += [HERE.parent / "piper_sdk" / "urdf",
                       HERE.parent / "piper_control" / "piper_sdk" / "urdf",
                       HERE.parent / "piper_cpp_sdk" / "piper_sdk" / "urdf"]
    for c in candidates:
        c = pathlib.Path(c)
        if (c / "piper.urdf").is_file():
            return c.resolve()
    if arg:
        sys.exit(f"error: no piper.urdf in {arg}")
    return None


def load_overlay(model):
    def load(name):
        return json.loads((HERE / "overlay" / name).read_text())
    return load("materials.json")["materials"], load(f"{model}.json")["links"], load("agx_gripper.json")["links"]


def add_geometry(link, spec, model, mesh_prefix, materials):
    """Insert <visual> and <collision> after the link's <inertial>."""
    if spec["material"] not in materials:
        sys.exit(f"overlay: unknown material {spec['material']}")
    origin = spec.get("origin", {})
    items = []
    for tag in ("visual", "collision"):
        e = ET.Element(tag)
        ET.SubElement(e, "origin", rpy=origin.get("rpy", "0 0 0"), xyz=origin.get("xyz", "0 0 0"))
        mesh = spec.get("collision", spec["mesh"]) if tag == "collision" else spec["mesh"]
        ET.SubElement(ET.SubElement(e, "geometry"), "mesh", filename=mesh_prefix + mesh.replace("{model}", model))
        if tag == "visual":
            ET.SubElement(e, "material", name=spec["material"])
        items.append(e)
    pos = 0
    for i, child in enumerate(link):
        if child.tag == "inertial":
            pos = i + 1
    for k, e in enumerate(items):
        link.insert(pos + k, e)


def build(src, model, mesh_prefix, kind):
    tree = ET.parse(src)
    robot = tree.getroot()
    materials, arm, grip = load_overlay(model)
    specs = dict(arm)
    if robot.find("link[@name='flange_link']") is not None:
        specs.update(grip)
    used = set()
    for link in robot.findall("link"):
        name = link.get("name")
        if name in specs:
            add_geometry(link, specs[name], model, mesh_prefix, materials)
            used.add(name)
        elif link.find("inertial") is not None:
            sys.exit(f"{src}: link {name} has no entry in overlay/{model}.json or overlay/agx_gripper.json")
    missing = set(specs) - used
    if missing:
        sys.exit(f"{src}: overlay links not in the URDF: {sorted(missing)}")
    for k, (name, rgba) in enumerate(materials.items()):
        m = ET.Element("material", name=name)
        ET.SubElement(m, "color", rgba=rgba)
        robot.insert(k, m)
    ET.indent(tree, space="  ")
    name = robot.get("name")
    header = (f"<?xml version=\"1.0\"?>\n<!-- Generated by {PKG}/scripts/generate_urdfs.py from the SDK's {name}.urdf "
              f"(kinematics, inertials) and overlay/ (meshes, materials). Do not edit.\n"
              + ("     Meshes as package://, for ROS and RViz." if kind == "ros" else
                 "     Full model for simulators: meshes relative to this file, movable gripper joints, no ROS needed.")
              + " -->\n")
    return header + ET.tostring(robot, encoding="unicode") + "\n"


def generate(sdk_dir, out):
    for kind, prefix in (("ros", f"package://{PKG}/meshes/"), ("sim", "../../../meshes/")):
        (out / kind).mkdir(parents=True, exist_ok=True)
        for model in MODELS:
            for suffix in ("", "_gripper"):
                name = model + suffix
                src = sdk_dir / f"{name}.urdf"
                if not src.is_file():
                    sys.exit(f"error: {src} not found")
                (out / kind / f"{name}.urdf").write_text(build(src, model, prefix, kind))


def same_tree(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.diff_files:
        return False
    return all(same_tree(a / d, b / d) for d in cmp.common_dirs)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sdk-urdf-dir")
    ap.add_argument("--out", default=str(HERE / "urdf" / "generated"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sdk = find_sdk_urdf_dir(args.sdk_urdf_dir)
    out = pathlib.Path(args.out)
    if sdk is None:
        print("SKIP: no SDK URDF directory (use --sdk-urdf-dir or PIPER_SDK_URDF_DIR, or place this package "
              "in the piper_control checkout)")
        sys.exit(77 if args.check else 1)
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            generate(sdk, pathlib.Path(tmp))
            if not out.is_dir() or not same_tree(out, pathlib.Path(tmp)):
                print(f"{out} is out of date w.r.t. {sdk}: run scripts/generate_urdfs.py")
                sys.exit(1)
        print(f"up to date ({sdk})")
        return
    generate(sdk, out)
    print(f"generated {out} from {sdk}")


if __name__ == "__main__":
    main()
