#!/usr/bin/env bash
# Regenerate the plain URDFs in piper_sdk_description/urdf/generated/ from its xacros: no
# xacro, no ROS, no meshes; kinematics and inertials only. The xacros stay the only source:
# piper_sdk compiles these files into its gravity compensation (cmake/gravity.cmake), and a
# test of this package fails when they are out of date (rerun this script after editing a
# xacro).
#
#   usage: generate_plain_urdfs.sh [gripper_opening_m=0.035] [out_dir=urdf/generated]
#
# For each model (piper, piper_h, piper_l, piper_x), two files:
#   <model>.urdf          the arm alone (base_link .. link6)
#   <model>_gripper.urdf  with the AgileX gripper; its prismatic joints (the jaw opening
#                         "gripper" and the mimicking fingers) become fixed joints at the given
#                         opening, so the fingers are a lumped, rigid mass on the flange.
# Needs ROS 2 Jazzy's xacro (sourced here) and python3. Nothing at run time needs ROS: the
# SDK library embeds these files (piper_sdk/cmake/gravity.cmake).
set -euo pipefail

opening="${1:-0.035}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
pkg="$(cd "$here/.." && pwd)"
desc="$pkg/urdf"
out="${2:-$pkg/urdf/generated}"

if ! command -v xacro >/dev/null 2>&1; then
    # shellcheck disable=SC1091
    set +u && source /opt/ros/jazzy/setup.bash && set -u
fi
command -v xacro >/dev/null || { echo "error: xacro not found (ROS 2 Jazzy: ros-jazzy-xacro)" >&2; exit 1; }

# The xacros include each other through $(find piper_sdk_description), which needs the package
# installed; point them at the source tree instead.
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
for f in "$desc"/*.xacro; do
    sed "s#\$(find piper_sdk_description)/urdf#$tmp#g" "$f" >"$tmp/$(basename "$f")"
done

mkdir -p "$out"
for model in piper piper_h piper_l piper_x; do
    for gripper in false true; do
        name="$model"
        [[ "$gripper" == true ]] && name="${model}_gripper"
        xacro "$tmp/piper_description.urdf.xacro" model:="$model" with_gripper:="$gripper" -o "$tmp/$name.raw.urdf"
        /usr/bin/env python3 - "$tmp/$name.raw.urdf" "$out/$name.urdf" "$model" "$gripper" "$opening" <<'EOF'
import math
import sys
import xml.etree.ElementTree as ET

src, dst, model, gripper, opening = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4] == "true", float(sys.argv[5])
tree = ET.parse(src)
robot = tree.getroot()

# Meshes and looks are not needed for gravity: drop them.
for link in robot.findall("link"):
    for tag in ("visual", "collision"):
        for e in link.findall(tag):
            link.remove(e)
for e in robot.findall("material"):
    robot.remove(e)


def rpy_matrix(r, p, y):
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return [[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
            [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
            [-sp, cp * sr, cp * cr]]


# Gripper: the jaw opening and the mimicking fingers become fixed at `opening`.
values = {"gripper": opening}
joints = {j.get("name"): j for j in robot.findall("joint")}
for name, j in joints.items():
    m = j.find("mimic")
    if m is not None:
        values[name] = float(m.get("multiplier", "1")) * opening + float(m.get("offset", "0"))
for name, j in joints.items():
    if j.get("type") != "prismatic":
        continue
    if name not in values:
        sys.exit(f"unexpected prismatic joint {name}")
    origin = j.find("origin")
    xyz = [float(v) for v in origin.get("xyz", "0 0 0").split()]
    rpy = [float(v) for v in origin.get("rpy", "0 0 0").split()]
    axis = [float(v) for v in j.find("axis").get("xyz").split()]
    R = rpy_matrix(*rpy)
    d = values[name]
    xyz = [xyz[i] + d * sum(R[i][k] * axis[k] for k in range(3)) for i in range(3)]
    origin.set("xyz", " ".join(f"{0.0 if abs(v) < 1e-9 else v:.9g}" for v in xyz))
    j.set("type", "fixed")
    for tag in ("axis", "limit", "mimic", "dynamics"):
        for e in j.findall(tag):
            j.remove(e)

robot.set("name", model + ("_gripper" if gripper else ""))
ET.indent(tree, space="  ")
header = (f"<?xml version=\"1.0\"?>\n<!-- Generated by piper_sdk_description/scripts/generate_plain_urdfs.sh from the xacros "
          f"(model:={model} with_gripper:={str(gripper).lower()}). Do not edit: edit the xacro, rerun the script.\n"
          f"     Kinematics and inertials only (no meshes), e.g. for gravity compensation."
          + (f"\n     Gripper joints fixed at a jaw opening of {opening:g} m (fingers {opening / 2:g} m each)." if gripper else "")
          + " -->\n")
with open(dst, "w") as f:
    f.write(header + ET.tostring(robot, encoding="unicode") + "\n")
print(f"  {dst}")
EOF
    done
done
