#!/usr/bin/env python3
"""Regenerate this package's URDF and meshes from AgileX's agx_arm_urdf.

    python3 import_agx_arm_urdf.py /path/to/agx_arm_urdf

For each Piper model it writes urdf/<model>.xacro, a macro with the arm's links and joints
(base_link .. link6, no "world" link), and copies the STL meshes to meshes/<model>/. The STL
files serve as visual and collision geometry (the upstream DAE visuals are ~4x larger); colours
come from materials. The AgileX gripper goes to urdf/agx_gripper.xacro and meshes/agx_gripper/.
"""

import argparse
import pathlib
import re
import shutil
import xml.etree.ElementTree as ET

MODELS = ["piper", "piper_h", "piper_l", "piper_x"]
PKG = "piper_sdk_description"
HERE = pathlib.Path(__file__).resolve().parent.parent

HEADER = """<?xml version="1.0"?>
<!-- Generated by scripts/import_agx_arm_urdf.py from AgileX agx_arm_urdf ({src}, MIT License).
     Do not edit by hand: re-run the script. -->
"""


def mesh_name(filename):
    return pathlib.Path(filename).stem  # .../dae/link1.dae or .../link1.stl -> link1


def rewrite_meshes(elem, model_dir):
    for mesh in elem.iter("mesh"):
        mesh.set("filename", f"package://{PKG}/meshes/{model_dir}/{mesh_name(mesh.get('filename'))}.stl")


def add_material(link, name):
    visual = link.find("visual")
    if visual is not None and visual.find("material") is None:
        ET.SubElement(visual, "material", name=name)


def indent_xml(elem):
    ET.indent(elem, space="  ")
    return ET.tostring(elem, encoding="unicode")


def import_arm(src, model):
    tree = ET.parse(src / model / "urdf" / f"{model}_description.urdf")
    robot = tree.getroot()
    macro = ET.Element("xacro:macro", name=f"{model}_body", params="")
    for child in list(robot):
        if child.tag == "link" and child.get("name") == "world":
            continue
        if child.tag == "joint" and child.get("name") == "world_to_base_link":
            continue
        if child.tag not in ("link", "joint"):
            continue
        rewrite_meshes(child, model)
        if child.tag == "link":
            add_material(child, "piper_base" if child.get("name") == "base_link" else "piper_link")
        macro.append(child)
    body = indent_xml(macro)
    out = HEADER.format(src=f"{model}/urdf/{model}_description.urdf")
    out += '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">\n'
    out += "  " + body.replace("\n", "\n  ") + "\n</robot>\n"
    (HERE / "urdf" / f"{model}.xacro").write_text(out)

    dst = HERE / "meshes" / model
    dst.mkdir(parents=True, exist_ok=True)
    for stl in sorted((src / model / "meshes").glob("*.stl")):
        shutil.copy2(stl, dst / stl.name)


def import_gripper(src):
    """Flange and gripper from piper_with_gripper_description.xacro, as a macro with the
    gripper's mounting yaw (Piper X mounts it a quarter turn round) as a parameter."""
    text = (src / "piper" / "urdf" / "piper_with_gripper_description.xacro").read_text()
    text = re.sub(r"<xacro:include[^>]*/>", "", text)
    robot = ET.fromstring(text)
    macro = ET.Element("xacro:macro", name="agx_gripper", params="parent mount_yaw:=0")
    for child in list(robot):
        if child.tag not in ("link", "joint"):
            continue
        rewrite_meshes(child, "agx_gripper" if child.get("name", "").startswith("gripper") else "flange")
        if child.tag == "joint" and child.get("name") == "flange_joint":
            child.find("parent").set("link", "${parent}")
        if child.tag == "joint" and child.get("name") == "gripper_base_joint":
            origin = child.find("origin")
            origin.set("rpy", "0 0 ${mount_yaw}")
        if child.tag == "link":
            add_material(child, "piper_link" if child.get("name") in ("flange_link", "gripper_base") else "piper_finger")
        macro.append(child)
    body = indent_xml(macro)
    out = HEADER.format(src="piper/urdf/piper_with_gripper_description.xacro")
    out += '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">\n'
    out += "  " + body.replace("\n", "\n  ") + "\n</robot>\n"
    # The flange mesh is per model; the arm xacro passes its mesh directory.
    out = out.replace(f"package://{PKG}/meshes/flange/flange.stl", f"package://{PKG}/meshes/${{flange_model}}/flange.stl")
    out = out.replace('params="parent mount_yaw:=0"', 'params="parent flange_model mount_yaw:=0"')
    (HERE / "urdf" / "agx_gripper.xacro").write_text(out)

    dst = HERE / "meshes" / "agx_gripper"
    dst.mkdir(parents=True, exist_ok=True)
    for stl in sorted((src / "agx_gripper" / "meshes").glob("*.stl")):
        shutil.copy2(stl, dst / stl.name)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("src", type=pathlib.Path, help="agx_arm_urdf checkout")
    args = parser.parse_args()
    for model in MODELS:
        import_arm(args.src, model)
    import_gripper(args.src)
    print("imported", ", ".join(MODELS), "and agx_gripper into", HERE)


if __name__ == "__main__":
    main()
